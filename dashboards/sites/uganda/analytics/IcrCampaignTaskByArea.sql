-- Campaign tasks with two places in the location hierarchy: the Location the task acts on
-- (for_location_id, columns prefixed for_) and the Location where the work happens (location_id,
-- columns prefixed location_). country is the for Location's. Rows whose Locations are not in the
-- hierarchy are kept, with those columns empty.
SELECT t.task_id,
       t.status,
       t.intent,
       t.code,
       t.campaign_id,
       t.activity,
       t.for_location_id,
       t.for_group_id,
       t.location_id,
       t.owner_team_id,
       t.strategy,
       t.origin,
       t.lineage,
       t.execution_start,
       t.execution_end,
       t.last_modified,
       t.treated_count,
       t.houses_visited,
       t.eligible_present,
       t.eligible_absent,
       t.children_already_marked,
       t.missed_reason,
       t.status_reason,
       t.activity_key,
       f.name AS for_name,
       f.admin_level AS for_admin_level,
       f.admin0_name AS for_admin0_name,
       f.admin1_name AS for_admin1_name,
       f.admin2_name AS for_admin2_name,
       f.admin3_name AS for_admin3_name,
       f.admin4_name AS for_admin4_name,
       f.admin0_code AS for_admin0_code,
       f.admin1_code AS for_admin1_code,
       f.admin2_code AS for_admin2_code,
       f.admin3_code AS for_admin3_code,
       f.admin4_code AS for_admin4_code,
       f.path AS for_path,
       l.name AS location_name,
       l.admin_level AS location_admin_level,
       l.admin0_name AS location_admin0_name,
       l.admin1_name AS location_admin1_name,
       l.admin2_name AS location_admin2_name,
       l.admin3_name AS location_admin3_name,
       l.admin4_name AS location_admin4_name,
       l.admin0_code AS location_admin0_code,
       l.admin1_code AS location_admin1_code,
       l.admin2_code AS location_admin2_code,
       l.admin3_code AS location_admin3_code,
       l.admin4_code AS location_admin4_code,
       l.path AS location_path,
       f.country
FROM task AS t
LEFT JOIN hierarchy AS f ON f.id = t.for_location_id
LEFT JOIN hierarchy AS l ON l.id = t.location_id
